INSERT INTO skill_aliases (alias_name, skill_id)
SELECT seed.alias_name, s.skill_id
FROM seed_skill_aliases seed
         JOIN skills s ON s.skill_name = seed.canonical_name
WHERE NOT EXISTS (SELECT 1 FROM skill_aliases a WHERE a.alias_name = seed.alias_name)
  AND NOT EXISTS (SELECT 1 FROM skills c WHERE c.skill_name = seed.alias_name);
SET @added_aliases = ROW_COUNT();

-- An empty result means no existing alias disagrees with this proposed mapping.
SELECT seed.alias_name, s.skill_name AS proposed_skill, old.skill_name AS existing_skill
FROM seed_skill_aliases seed
         JOIN skills s ON s.skill_name = seed.canonical_name
         JOIN skill_aliases a ON a.alias_name = seed.alias_name
         JOIN skills old ON old.skill_id = a.skill_id
WHERE a.skill_id <> s.skill_id;

COMMIT;
SELECT @added_skills AS added_skills, @added_aliases AS added_aliases;


